class Basics:
    def draw_line(self, x1, y1, x2, y2, color):
        dx = abs(x2 - x1)
        dy = abs(y2 - y1)
        sx = 1 if x1 < x2 else -1
        sy = 1 if y1 < y2 else -1
        err = dx - dy
        
        points = []
        x, y = x1, y1
        
        while True:
            self.putpixel(x, y, color)
            if x == x2 and y == y2:
                break
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x += sx
            if e2 < dx:
                err += dx
                y += sy
        
        return points
    
    def draw_rectangle(self, x, y, width, height, color):
        if width < 0:
            x += width
            width = abs(width)
        if height < 0:
            y += height
            height = abs(height)
        for i in range(width):
            for j in range(height):
                self.putpixel(x + i, y + j, color)

    def draw_char(self, x, y, char, color, scale=1):
        map_char = _FONT_5X7.get(char.upper(), _FONT_5X7["?"])
        for i in range(len(map_char)):
            for j in range(len(map_char[i])):
                if map_char[i][j] == "1":
                    px = x + j * scale
                    py = y + i * scale
                    self.draw_rectangle(px, py, scale, scale, color)

    def draw_text(self, x, y, text, color, scale=1):
        cursor_x = x
        for char in text:
            self.draw_char(cursor_x, y, char, color, scale)
            cursor_x += 6 * scale
            
            
    def drawCirclePoints(self, x, y, xc, yc, color):
        self.putpixel(xc+x, yc+y, color)
        self.putpixel(xc-x, yc+y, color)
        self.putpixel(xc+x, yc-y, color)
        self.putpixel(xc-x, yc-y, color)
        self.putpixel(xc+y, yc+x, color)
        self.putpixel(xc-y, yc+x, color)
        self.putpixel(xc+y, yc-x, color)
        self.putpixel(xc-y, yc-x, color)


    def draw_circle(self, xc, yc, r, color):
        x = 0
        y = r
        d = 3 - 2 * r
        self.drawCirclePoints(x, y, xc, yc, color)
        while (y >= x):
            if (d > 0):
                y -= 1
                d = d + 4 * (x - y) + 10
            else:
                d = d + 4 * x + 6
            x += 1
            self.drawCirclePoints(x, y, xc, yc, color)
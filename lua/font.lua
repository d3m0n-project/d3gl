local PIXELS = {}
for char, rows in pairs(GLYPHS) do
    local pixels = {}
    for y = 1, #rows do
        local row = rows[y]
        for x = 1, #row do
            if row:sub(x, x) == "1" then
                pixels[#pixels + 1] = x - 1
                pixels[#pixels + 1] = y - 1
            end
        end
    end
    PIXELS[char] = pixels
end

function font.glyph(char)
    return PIXELS[char] or PIXELS[char:upper()] or PIXELS["?"]
end

function font.measure(text, scale)
    scale = scale or 1
    local lines, longest = 0, 0
    for line in (text .. "\n"):gmatch("(.-)\n") do
        lines = lines + 1
        if #line > longest then longest = #line end
    end
    local width = longest > 0 and (longest * font.ADVANCE - 1) * scale or 0
    local height = (lines * font.LINE_HEIGHT - 2) * scale
    return width, height
end

return font
